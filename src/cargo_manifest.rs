//! Declarative changeset model for the `Cargo.toml` files the tool writes source against: the
//! three generated crates' manifests plus the `--export-static-crate` target's.
//!
//! The manifests (`rust/Cargo.toml`, `wasm/Cargo.toml`, `wasm/json-gen/Cargo.toml`, and the
//! static-runtime crate's) are not whole-file writes. Each run the tool declares an ordered set of [`ManifestOp`]s over TOML
//! key paths and *applies* them ([`apply`]) to whatever manifest already exists on disk (or to an
//! empty document on first run). Keys no op mentions are never touched, so user-added dependencies,
//! `[profile]` sections, comments, blank lines, and formatting all survive regeneration
//! byte-for-byte (`toml_edit` preserves each node's decor). This is the same contract `cargo add` /
//! `cargo remove` make on user-owned manifests, and they use the same crate underneath.
//!
//! The three op kinds are the per-field collision rules:
//! * [`ManifestOp::Set`] — tool-owned key: written every run, overwriting whatever is there. User
//!   edits to these are overwritten by design (the dep set is version-coupled to the emitted code).
//!   **Three** path classes are exceptions, all merging into the existing value instead of replacing
//!   it:
//!   - `["dependencies", <name>]` merges FIELD-LEVEL ([`merge_dep_spec`]), so a user's
//!     `optional`/`default-features`/extra features and a compatible version pin survive a regen
//!     while the tool still owns the version floor, its required features, and any field it sets
//!     (e.g. `path`). The one axis a merge can be told to OWN outright is the dep's SOURCE: a spec
//!     carrying `git` asserts it implicitly, and a registry-version spec asserts it by carrying
//!     `assert_source` (a crates.io version has no cargo key that could express the intent), which
//!     clears a stale `git`/`rev`/`path`/… off an already-written entry instead of flooring against
//!     it. See [`merge_dep_spec`] for the exact merge contract. A merged entry is the one
//!     place the byte-for-byte claim above is qualified, in two bounded ways: its inline table's
//!     whitespace is re-normalized ([`normalize_inline_decor`] — the merge moves fields between
//!     positions, so their old spacing is stale by construction), and a dependency the tool ADDS to
//!     a `[dependencies]` table that already existed gains an [`OWNERSHIP_MARKER`].
//!   - `["features", "default"]` merges as a UNION ([`merge_default_features`]): the user's list
//!     survives verbatim and tool entries it lacks are appended. A whole-value replace would
//!     silently drop a consumer's customized default-feature list, and the key is not one the tool
//!     can decline to write — the generated crate's `std` feature has to be on by default for a
//!     plain `cargo build` to keep working.
//!   - `["features", "std"]` merges as a union too, plus an ABSENT-DEP PRUNE
//!     ([`merge_std_features`]): a `<pkg>/<feat>` entry whose `<pkg>` is not a key of the document's
//!     `[dependencies]` table when the op applies is dropped from either side. The tool's `std` list
//!     is COMPUTED per run from the deps that run wrote, so unlike `default`'s constant list it
//!     varies with the flags, and a union alone would strand yesterday's `serde/std` beside a
//!     tombstoned dep — a manifest cargo rejects. This is why the `features.std` op is pushed AFTER
//!     every dependencies op in every builder.
//!
//!   The `features.std` path additionally carries a tool-asserted COMMENT
//!   ([`STD_OWNERSHIP_COMMENT`]): the co-ownership contract, restated above the key on every run
//!   that writes it, so the rule is legible to whoever edits the file rather than only to a reader
//!   of this repo's docs. It reads the key's existing comment lines to preserve the user's — the
//!   same bounded existing-manifest read the merges above perform, and like them a pure function of
//!   `(ops, existing)`.
//!
//!   Every other `Set` path hard-replaces as before.
//! * [`ManifestOp::SeedOnce`] — written only if the key is absent (existence check only, never a
//!   content read), so it stays on the safe side of the determinism line. `package.version` is the
//!   one seeded key: the tool has no opinion on it after the initial `0.1.0`/`0.0.1`.
//! * [`ManifestOp::Remove`] — tombstone: a key the tool once managed and no longer wants, deleted if
//!   present (with empty parent tables garbage-collected). Tombstones are kept forever (one line
//!   each) so a manifest generated by any old tool version converges on regeneration.
//!
//! **The unconditional ops come from an append-only change LOG**, one per manifest
//! (`static/manifest_changes/{rust,wasm,json_gen,static_runtime}.toml`) — the single source of truth. Each log is
//! an ordered list of entries, each an `id` + dotted `path` + exactly one of `set` / `seed` /
//! `remove`, plus the optional `assert_source = true` modifier (`set` on a `dependencies.*` path
//! only). [`fold_log`] folds them per-path last-write-wins (final `set` → [`ManifestOp::Set`],
//! final `seed` → [`ManifestOp::SeedOnce`], final `remove` → [`ManifestOp::Remove`], i.e. a dropped
//! key is auto-tombstoned) and emits the folded ops in first-mention order of each path. Editing is
//! append-only: to change a key you append another entry, to drop one you append a `remove` — so the
//! log records the full history and a key the tool ever managed can never be silently unmentioned
//! (the property the old separate ledger enforced is now structural). Contiguous ids, one-of per
//! entry, and a misplaced `assert_source` are hard errors naming the log file. The `static/Cargo_{rust,wasm,json_gen,static_runtime}.toml`
//! files are *derived* from the log ([`render_derived_template`]) as a human-readable snapshot of
//! the current live keys — generated, never read at runtime, kept in sync by a drift gate.
//!
//! Flag/type-conditional deps in the generated-crate changesets emit **set-or-remove, never
//! set-or-skip**: e.g. `--preserve-encodings` false emits `Remove(dependencies.hashlink)`,
//! so flipping a flag off doesn't strand a stale dep. That rule is available only because the tool
//! knows every such dep's NAME independently of the flag's value, so it can tombstone one it no
//! longer wants — which is also why a dep the tool has stopped using entirely (a renamed backing
//! crate, say) can carry an UNCONDITIONAL `Remove` forever, the in-code twin of a change-log
//! tombstone. Two kinds of entry fall outside it and are assert-only: [`ops_for_static_runtime`],
//! whose manifest is co-owned with a hand-owned crate the tool cannot speak for, and the
//! `<package>=<path>` dependency entries [`manifest_dep_ops`] builds for `--rust-dep`, `--wasm-dep`
//! and `--json-gen-dep`, whose package names exist only inside the flag values — a dropped flag
//! carries no name to tombstone. Both document the stale-entry consequence where a user meets it.
//! An unparseable existing manifest is a hard error naming the file — never a silent clobber,
//! since a parse failure is exactly the case where the user has content we can't safely preserve.

