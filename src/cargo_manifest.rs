    /// The tombstone's teeth. Regenerating over a manifest written BEFORE `OrderedHashMap`'s
    /// backing moved to `hashlink` must both assert the new dep and delete the old one, so a user
    /// who upgrades the tool converges instead of carrying a dep nothing references any more. The
    /// changeset comes from the production `ops_for_rust`, not a hand-listed pair, so deleting the
    /// unconditional `Remove` from it fails here (a hand-rebuilt op pair would assert nothing about
    /// the real list), at the cost of reading the repo's own change log — same idiom as
    /// `warmup_manifest_covers_registry_dep_universe`.
    #[test]
    fn hashlink_swap_tombstones_the_pre_swap_dep() {
        use clap::Parser;
        let ops_for = |extra: &[&str]| {
            let mut args = vec![
                "cddl-codegen",
                "--input",
                "unused",
                "--output",
                "unused",
                "--static-dir",
                concat!(env!("CARGO_MANIFEST_DIR"), "/static"),
            ];
            args.extend_from_slice(extra);
            let cli = Cli::parse_from(args);
            ops_for_rust(&IntermediateTypes::new(), false, &cli).unwrap()
        };

        let on = apply(
            &ops_for(&["--preserve-encodings=true"]),
            Some(cml_shaped_manifest()),
            "rust/Cargo.toml",
        )
        .unwrap();
        assert!(
            on.contains("hashlink = "),
            "the new backing dep must be asserted:\n{on}"
        );
        assert!(
            !on.contains("linked-hash-map"),
            "the pre-swap dep must be tombstoned:\n{on}"
        );
        // Not a vacuous pass: the changeset really was applied to this base.
        assert!(on.contains("cbor_event"), "changeset not applied:\n{on}");

        // The tombstone is UNCONDITIONAL, unlike the set-or-remove flag deps: with the flag off the
        // stale dep goes just the same, and no backing dep replaces it.
        let off = apply(
            &ops_for(&[]),
            Some(cml_shaped_manifest()),
            "rust/Cargo.toml",
        )
        .unwrap();
        assert!(
            !off.contains("linked-hash-map"),
            "the tombstone must not be conditional on the flag:\n{off}"
        );
        assert!(
            !off.contains("hashlink"),
            "hashlink is preserve-encodings-only:\n{off}"
        );
    }

    // ---- alloc-mode dep specs (the reshaped JSON/hex specs) ----------------------------------

    /// The four specs `ops_for_rust` asserts in alloc mode, keyed by dep name. Read from the
    /// PRODUCTION function rather than restated, so a spec that drifts fails the merge tests below
    /// instead of leaving them asserting a form the tool no longer emits. Every flag that gates one
    /// of them is on, and `export_raw_bytes_encoding_trait` forces `hex`.
    fn alloc_mode_spec(name: &str) -> String {
        use clap::Parser;
        let cli = Cli::parse_from([
            "cddl-codegen",
            "--input=unused",
            "--output=unused",
            concat!("--static-dir=", env!("CARGO_MANIFEST_DIR"), "/static"),
            "--json-serde-derives=true",
            "--json-schema-export=true",
        ]);
        let ops = ops_for_rust(&IntermediateTypes::new(), true, &cli).unwrap();
        let op = op_at(&ops, &["dependencies", name])
            .unwrap_or_else(|| panic!("`{name}` is not in the rust changeset"));
        match op {
            ManifestOp::Set { value, .. } => value.to_string().trim().to_owned(),
            other => panic!("`{name}` is {other:?}, expected a Set"),
        }
    }

    /// Every reshaped dep really is in alloc mode in the shipped changeset. The merge tests below
    /// are only meaningful while this holds, and it is the one property a snapshot bless could
    /// silently ratify away.
    #[test]
    fn the_json_and_hex_deps_are_asserted_in_alloc_mode() {
        for (name, feature) in [
            ("serde", "alloc"),
            ("serde_json", "alloc"),
            ("hex", "alloc"),
            // schemars has no `alloc` feature; `derive` is what its default set contributed.
            ("schemars", "derive"),
        ] {
            let spec = alloc_mode_spec(name);
            assert!(
                spec.contains("default-features = false"),
                "`{name}` must be asserted with default features off, got: {spec}"
            );
            assert!(
                spec.contains(feature),
                "`{name}` must name `{feature}` explicitly once defaults are off, got: {spec}"
            );
        }
    }

